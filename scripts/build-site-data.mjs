#!/usr/bin/env node
// Generates site/data.js from the SAME sources the product runs on:
// brain/agents/*.md (what each agent is, its colour, glyph, workflows)
// and brain/blueprints/*.json (which agents a vertical gets, which one
// is the hero, which dashboard tabs exist).
//
// Why this exists: the website's whole claim is "this is the actual
// thing you get." A hand-written marketing page drifts from the product
// within a month — a new agent ships and the site never hears about it.
// Regenerating from the engine's own files means the site is wrong only
// if the product is wrong.
//
// Usage:  node scripts/build-site-data.mjs
// Output: site/data.js  (sets window.SAILZ_DATA — a plain <script> tag,
//         no fetch, so the site also works opened straight off disk)

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const AGENTS_DIR = path.join(ROOT, "brain", "agents");
const BLUEPRINTS_DIR = path.join(ROOT, "brain", "blueprints");
const OUT = path.join(ROOT, "site", "data.js");

// Same flat key: value frontmatter shape server/brain.js parses. Kept
// deliberately independent of that module (it's CommonJS and pulls in
// the instance layer, which has no business running in a build script)
// — if the two ever disagree, brain.js is authoritative and this is the
// bug.
function parseFrontmatter(raw) {
  const m = raw.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!m) return { data: {}, body: raw.trim() };
  const data = {};
  for (const line of m[1].split(/\r?\n/)) {
    const idx = line.indexOf(":");
    if (idx === -1 || !line.trim()) continue;
    const key = line.slice(0, idx).trim();
    let val = line.slice(idx + 1).trim();
    if (val === "null" || val === "~" || val === "") { data[key] = null; continue; }
    if (/^".*"$/.test(val) || /^'.*'$/.test(val)) val = val.slice(1, -1);
    data[key] = val;
  }
  return { data, body: m[2].trim() };
}

// "- **Answer Calls** — Answer inbound calls on the clinic line"
//   → { label: "Answer Calls", detail: "Answer inbound calls…" }
// Plain bullets (older files) degrade to label-only rather than break.
function workflowsFrom(body) {
  const start = /^##\s+Workflows\s*$/mi.exec(body);
  if (!start) return [];
  const rest = body.slice(start.index + start[0].length);
  const next = rest.search(/^##\s+/m);
  return (next === -1 ? rest : rest.slice(0, next))
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l.startsWith("-"))
    .map((l) => {
      const line = l.replace(/^-+\s*/, "");
      const m = line.match(/^\*\*(.+?)\*\*\s*[—–-]\s*(.+)$/);
      return m ? { label: m[1].trim(), detail: m[2].trim() } : { label: line.slice(0, 40), detail: line };
    });
}

const agents = {};
for (const file of fs.readdirSync(AGENTS_DIR).filter((f) => f.endsWith(".md"))) {
  const { data, body } = parseFrontmatter(fs.readFileSync(path.join(AGENTS_DIR, file), "utf8"));
  if (!data.name) continue;
  agents[data.name] = {
    id: data.name,
    name: data.displayName || data.name,
    tagline: data.tagline || "",
    description: data.description || "",
    color: data.color || "#c9a066",
    glyph: data.glyph || "◇",
    tools: (data.tools || "").split(",").map((s) => s.trim()).filter(Boolean),
    schedule: data.schedule || null,
    workflows: workflowsFrom(body),
  };
}

const blueprints = fs
  .readdirSync(BLUEPRINTS_DIR)
  .filter((f) => f.endsWith(".json"))
  .map((f) => JSON.parse(fs.readFileSync(path.join(BLUEPRINTS_DIR, f), "utf8")));

// Fail loudly rather than shipping a map with a hole in it: a blueprint
// naming an agent that no longer exists would silently render as a
// missing node, which is exactly the kind of quiet drift this script is
// supposed to prevent.
const missing = [];
for (const bp of blueprints) {
  for (const id of [...(bp.agents || []), ...(bp.dormant || [])]) {
    if (!agents[id]) missing.push(`${bp.vertical} → ${id}`);
  }
}
if (missing.length) {
  console.error("Blueprint references agents that don't exist in brain/agents/:\n  " + missing.join("\n  "));
  process.exit(1);
}

// Display order on the site follows the blueprint list order (hero
// first), not brain/agents' `order` field — that field sequences the
// product's map, this sequences a sales argument.
const ORDER = ["dental", "restaurant", "financial-services", "hospitality", "local-service"];
blueprints.sort((a, b) => ORDER.indexOf(a.vertical) - ORDER.indexOf(b.vertical));

const payload = { generatedAt: new Date().toISOString(), agents, blueprints };

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(
  OUT,
  "// GENERATED by scripts/build-site-data.mjs — do not edit by hand.\n" +
    "// Source: brain/agents/*.md + brain/blueprints/*.json\n" +
    "window.SAILZ_DATA = " + JSON.stringify(payload, null, 2) + ";\n"
);

console.log(`site/data.js — ${Object.keys(agents).length} agents, ${blueprints.length} blueprints`);
